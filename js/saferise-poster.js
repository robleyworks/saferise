/* ============================================================================
   SafeRise -- js/saferise-poster.js
   prompt-galaxy-player.md -- the two-layer galaxy treatment for the guided-
   session player.

   Defines window.SRClearing = { mount(stage, audio, opts) }, the exact call
   shape js/sr-medplayer.js already invokes:

     if (root.SRClearing && root.SRClearing.mount) {
       root.SRClearing.mount(m.stage, m.audio, { warm: cfg.warm, cool: cfg.cool });
     }

   js/sr-medplayer.js is marked "supplied, not modified" (SR-393) and this
   pass's own brief never asks to touch it, so this file becomes the
   implementation behind the one extension point that already exists,
   rather than adding a second, competing mount path. It replaces
   js/sr-clearing-visual.js's abstract particle canvas; that file and its
   two <canvas class="sr-glow">/<canvas class="sr-field"> elements are left
   in place (still loaded, in case anything else ever calls SRClearing
   directly before this script), just hidden the moment this mounts.

   Depends on content/galaxy.js (GALAXY_POSTERS, generated by
   tools/mk_posters.py) having loaded first.

   ════════════════════════════════════════════
   THE GOVERNING RULE, ENFORCED IN JS TOO -- amended by
   prompt-galaxy-refinements.md #0, amended again by
   GALAXY-PLAYER-REFINEMENTS-v2.md #0
   ════════════════════════════════════════════
   This file never writes a `transform` inline style at all, on any
   element, ever -- every transform lives in a CSS keyframe or a computed
   `calc()`, not here. JS writes custom properties (--p, --amp, --release,
   --warmshift, --sr-ps-warm/-cool/-acc), a `playbackRate` on the subject/
   aura Animation objects (set once per mount now, not per tick -- v2 #1a
   holds the breath period for the whole session instead of ramping it),
   and an `animationName` selecting which of the three per-state keyframe
   variants runs (v2 #1b) -- never which property animates or by how much,
   so this still isn't writing a transform. The CSS keyframes themselves
   permit a translate on two elements beyond the five wander stars --
   .sr-ps-subject/.sr-ps-plain's `sr-ps-breatheA/U/N` and .sr-ps-aura's own
   `sr-ps-auraSwellA/U/N` -- each under ~1.8% of the frame, one element/one
   period/one curve each, per the amended rule. Section 7's verify step
   greps the emitted CSS for this. */

(function (root) {
  'use strict';

  var STEPS = ['Recognise', 'Regulate', 'Release', 'Rise'];
  var TICK_MS = 250; /* ~4Hz, per brief #4 -- --p does not need 60fps */

  function el(tag, cls) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    return n;
  }

  /* -------------------------------------------------- id from the audio src
     content/meditation.js's own rule: "the path lives here, never in
     markup", and audio filenames follow MEDITATION_BASE + '<id>-<slug>.mp3'.
     Extracting the id back out of audio.currentSrc is the only route
     available to this file, since js/sr-medplayer.js's build() never
     forwards cfg.key/cfg.id to SRClearing.mount() -- only warm/cool. */
  function idFromSrc(audio) {
    var src = audio.currentSrc || audio.src || '';
    var m = /\/(t\d-\d\d)-/.exec(src);
    return m ? m[1] : null;
  }

  function reducedMotion() {
    return root.matchMedia && root.matchMedia('(prefers-reduced-motion: reduce)').matches;
  }

  function warmShift() {
    var hr = new Date().getHours();
    return Math.max(0, Math.min(1, (hr - 8) / 14));
  }

  /* ---------------------------------------------------------- the breath
     GALAXY-PLAYER-REFINEMENTS-v2.md #1a/#1b -- two corrections to the
     original mockup, both rulings: the period is HELD for the whole
     session (no more easing every state toward a 10s target -- 10s is
     Agitated's own pair only, not a universal destination), and the peak
     keyframe position is per state (40% for Agitated's 4:6 ratio, 50% for
     Unsteady/Numb's even ratios). Source: the protocol's own `state`
     field in content/galaxy.js (GALAXY_POSTERS[id].state) -- read at mount
     time below, never `data-per` typed per player.

     Steady isn't in the brief's own table (it names Agitated/Unsteady/
     Numb only -- the three states that actually occur among the 30 track
     protocols; Steady only ever applies to t0-00). Judgment call, reported
     rather than silently assumed: Steady's own target has always been
     "4-in 6-out, already there" (SR-403's original framing) -- the same
     10s/40%-peak shape as Agitated -- so it reuses the 'A' keyframe/8
     held-seconds-map entry rather than inventing a fourth pair. */
  var STATE_HELD_BREATH = { Agitated: 10, Unsteady: 12, Numb: 8, Steady: 10 };
  var STATE_KEYFRAME = { Agitated: 'A', Unsteady: 'U', Numb: 'N', Steady: 'A' };

  /* Still Animation.playbackRate, never a duration rewrite (brief #1a: "The
     entrainment mechanism does not otherwise change"). The only change
     from SR-403/405's version is that this now runs ONCE, at mount, rather
     than every tick -- there is nothing left to ramp once the period is
     held for the whole session. Each CSS keyframe's own duration stays
     fixed at 10s regardless of which named variant is selected (see
     css/saferise-poster.css), so rate = 10 / heldSeconds reaches the true
     per-state period exactly once, with no phase jump. */
  function applyHeldBreath(elements, heldSeconds) {
    var rate = 10 / heldSeconds;
    elements.forEach(function (el) {
      if (!el || !el.getAnimations) return;
      var list = el.getAnimations();
      if (list.length) list[0].playbackRate = rate;
    });
    return rate;
  }

  /* ---------------------------------------------------------- audio aura
     One AnalyserNode per player, created on first play, its *analyser
     branch* disconnected on pause (source stays connected to destination
     throughout, or playback would go silent the moment Web Audio takes
     the routing over). Smoothed with a simple exponential moving average
     over the time-domain RMS -- reads as breath, not a level meter, per
     the brief's own instruction not to feed a raw FFT bin. */
  function makeAura(audio) {
    var ctx = null, analyser = null, source = null, data = null, smoothed = 0, connected = false;
    function ensure() {
      if (ctx) return;
      var Ctx = root.AudioContext || root.webkitAudioContext;
      if (!Ctx) return;
      ctx = new Ctx();
      source = ctx.createMediaElementSource(audio);
      analyser = ctx.createAnalyser();
      analyser.fftSize = 512;
      data = new Uint8Array(analyser.fftSize);
      source.connect(ctx.destination); /* always -- keeps audio audible */
    }
    function connectAnalyser() {
      ensure();
      if (!ctx || connected) return;
      source.connect(analyser);
      connected = true;
    }
    function disconnectAnalyser() {
      if (!connected) return;
      try { source.disconnect(analyser); } catch (e) {}
      connected = false;
    }
    function read() {
      if (!connected || !analyser) return smoothed;
      analyser.getByteTimeDomainData(data);
      var sum = 0;
      for (var i = 0; i < data.length; i++) {
        var v = (data[i] - 128) / 128;
        sum += v * v;
      }
      var rms = Math.sqrt(sum / data.length); /* 0..~1 */
      smoothed += (rms - smoothed) * 0.25; /* EMA, not a raw bin */
      return Math.max(0, Math.min(1, smoothed * 2.2));
    }
    function teardown() {
      disconnectAnalyser();
      if (ctx) { try { ctx.close(); } catch (e) {} }
    }
    return { connectAnalyser: connectAnalyser, disconnectAnalyser: disconnectAnalyser, read: read, teardown: teardown };
  }

  /* GALAXY-PLAYER-COMPLETE.md #5 -- the centred overlay (control, theme,
     title). Replaces SR-408's bare .sr-ps-ctrl -- that control's real-
     button/keyboard/aria-sync behaviour is kept, just wrapped and restyled
     (see css/saferise-poster.css). Built only when the caller opts in
     (opts.buildControl); js/sr-medplayer.js's own call never does, so the
     modal context (which already has .sr-medplayer__play, and its own
     .sr-medplayer__copy for title/eyebrow outside the stage) is
     unaffected -- building a second one there would be exactly the
     "parallel system" every brief in this series has ruled out.
     Disabled (no click handler bound at all, not just visually styled)
     when hasAudio is false -- honest state, per SR-406, not a fake
     control. theme/title are plain strings the caller already resolved
     from its own data (protocol.html reads them from PAGE_PROTOCOL --
     see that file -- not duplicated here). */
  /* FB-07 (PASS-fix-batch-01.md) · four bars, a restrained "voice speaking"
     signal. Height is written per-tick as a --v custom property from
     mount()'s own frame loop (see below), reusing the same aura.read()
     analyser value --amp already consumes -- one AnalyserNode, two
     readouts, not a second audio graph per player. */
  function buildVoice() {
    var voice = el('div', 'sr-ps-voice');
    voice.setAttribute('aria-hidden', 'true');
    for (var i = 0; i < 4; i++) voice.appendChild(el('i'));
    return voice;
  }

  function buildOverlay(stage, audio, hasAudio, theme, title) {
    var overlay = el('div', 'sr-ps-overlay');
    var ctrl = el('button', 'sr-ps-ctrl');
    ctrl.type = 'button';
    ctrl.appendChild(el('i'));
    overlay.appendChild(ctrl);
    var voice = buildVoice();
    overlay.appendChild(voice);
    if (theme) {
      var themeEl = el('p', 'sr-ps-theme');
      themeEl.textContent = theme;
      overlay.appendChild(themeEl);
    }
    if (title) {
      var titleEl = el('p', 'sr-ps-ptitle');
      titleEl.textContent = title;
      overlay.appendChild(titleEl);
    }
    stage.appendChild(overlay);

    if (!hasAudio) {
      ctrl.disabled = true;
      ctrl.setAttribute('aria-disabled', 'true');
      ctrl.setAttribute('aria-label', 'Guided audio not yet available for this protocol');
      return { overlay: overlay, voice: voice };
    }

    ctrl.setAttribute('aria-label', 'Play guided meditation');
    ctrl.addEventListener('click', function () {
      if (audio.paused) audio.play().catch(function () {});
      else audio.pause();
    });
    audio.addEventListener('play', function () {
      ctrl.setAttribute('data-playing', 'true');
      ctrl.setAttribute('aria-label', 'Pause guided meditation');
    });
    audio.addEventListener('pause', function () {
      ctrl.removeAttribute('data-playing');
      ctrl.setAttribute('aria-label', 'Play guided meditation');
    });
    audio.addEventListener('ended', function () {
      ctrl.removeAttribute('data-playing');
      ctrl.setAttribute('aria-label', 'Play guided meditation');
    });
    return { overlay: overlay, voice: voice };
  }

  /* #7 -- the lockup, this file's own build now (protocol.html's fully
     custom mount has no .sr-medplayer__lockup to reuse the way SR-406/408
     did). Confirmed no other lockup renders for this context before
     building one -- js/sr-medplayer.js's own lockup is scoped to its own
     modal stage, never this one. */
  function buildLock(stage) {
    var lock = el('div', 'sr-ps-lock');
    lock.setAttribute('aria-hidden', 'true');
    lock.appendChild(el('span', 'rule'));
    var mark = el('span', 'mark');
    mark.textContent = 'SAFERISE';
    lock.appendChild(mark);
    stage.appendChild(lock);
    return lock;
  }

  function fmtTime(s) {
    if (!isFinite(s) || s < 0) return '--:--';
    s = Math.floor(s);
    var m = Math.floor(s / 60), sec = s % 60;
    return m + ':' + (sec < 10 ? '0' : '') + sec;
  }

  /* FB-07 -- elapsed/total plus a seekable line. Native <input type=range>
     for the seek control (see css/saferise-poster.css for why: real
     keyboard support and the accessible value text come from the
     platform). Total reads from the media's own metadata, never
     hardcoded -- "--:--" until 'loadedmetadata' fires, per the brief.
     dragging tracks whether the member currently has a pointer/keyboard
     grip on the thumb, so the tick loop below doesn't fight their input
     by resetting .value out from under them mid-drag. */
  function buildTransport(stage, audio, hasAudio) {
    var wrap = el('div', 'sr-ps-transport');
    var time = el('div', 'sr-ps-time');
    var cur = el('span'); cur.textContent = '--:--';
    var sep = el('span', 'sep'); sep.textContent = '/';
    var tot = el('span'); tot.textContent = '--:--';
    time.appendChild(cur); time.appendChild(sep); time.appendChild(tot);
    var seek = el('input', 'sr-ps-seek');
    seek.type = 'range'; seek.min = '0'; seek.max = '1000'; seek.value = '0';
    seek.step = '1';
    seek.setAttribute('aria-label', 'Seek');
    seek.setAttribute('aria-valuetext', '0:00 of --:--');
    wrap.appendChild(time); wrap.appendChild(seek);
    stage.appendChild(wrap);

    if (!hasAudio) { seek.disabled = true; return { wrap: wrap, cur: cur, tot: tot, seek: seek, dragging: function () { return false; } }; }

    var dragging = false;
    seek.addEventListener('pointerdown', function () { dragging = true; });
    seek.addEventListener('pointerup', function () { dragging = false; });
    seek.addEventListener('keydown', function () { dragging = true; });
    seek.addEventListener('blur', function () { dragging = false; });
    seek.addEventListener('input', function () {
      var dur = audio.duration;
      if (!dur || !isFinite(dur)) return;
      var p = (+seek.value) / 1000;
      audio.currentTime = p * dur;
      cur.textContent = fmtTime(audio.currentTime);
      seek.style.setProperty('--sp', (p * 100).toFixed(2) + '%');
      seek.setAttribute('aria-valuetext', fmtTime(audio.currentTime) + ' of ' + fmtTime(dur));
    });
    seek.addEventListener('change', function () { dragging = false; });

    function onMeta() {
      tot.textContent = fmtTime(audio.duration);
      cur.textContent = fmtTime(audio.currentTime);
      seek.setAttribute('aria-valuetext', fmtTime(audio.currentTime) + ' of ' + fmtTime(audio.duration));
    }
    if (audio.readyState >= 1 && audio.duration) onMeta();
    audio.addEventListener('loadedmetadata', onMeta);

    return { wrap: wrap, cur: cur, tot: tot, seek: seek, dragging: function () { return dragging; } };
  }

  /* #4 -- the four-step bar, a sibling appended right after the stage
     (outside it, per the brief), not inside. Returns the four .sr-ps-seg
     elements so mount()'s own tick can drive them from the same idx/within
     it already computes for .sr-ps-stepnow -- one computation, two
     consumers, not two separate step trackers that could disagree. */
  function buildSteps(stage) {
    var bar = el('div', 'sr-ps-steps');
    var segs = STEPS.map(function (name) {
      var seg = el('span', 'sr-ps-seg');
      seg.appendChild(el('i'));
      var b = el('b');
      b.textContent = name;
      seg.appendChild(b);
      bar.appendChild(seg);
      return seg;
    });
    stage.insertAdjacentElement('afterend', bar);
    return segs;
  }

  /* GALAXY-PLAYER-COMPLETE.md #0/#2 -- field and clear are the SAME
     photograph on both tiers now (confirmed byte-identical in all four of
     the reference mockup's own players before relying on this -- see this
     pass's own report). The dissolve is pure CSS filter work on one
     shared <img> reference per layer (two <img> elements, same src), not
     a second asset. Full tier additionally gets a real .subject cutout
     that breathes independently; universal tier has no subject at all --
     the aura carries the breath alone (#2's own instruction), and that
     stays safe under the governing rule for the same reason the rule was
     amended in the first place: still one element, one period, one curve. */
  function buildLayers(stage, data, hasSubject) {
    var frag = document.createDocumentFragment();
    var photo = hasSubject ? data.field : data.cover;
    var photoClear = hasSubject ? data.clear : data.cover;

    var field = el('img', 'sr-ps-field'); field.src = photo; field.alt = '';
    var clear = el('img', 'sr-ps-clear'); clear.src = photoClear; clear.alt = '';
    var lights = el('div', 'sr-ps-lights');
    var wander = el('div', 'sr-ps-wander');
    for (var i = 0; i < 5; i++) wander.appendChild(el('i'));

    var subject = null;
    var subjwrap = null;
    if (hasSubject) {
      subjwrap = el('div', 'sr-ps-subjwrap');
      subject = el('img', 'sr-ps-subject'); subject.src = data.subject; subject.alt = '';
      subjwrap.appendChild(subject);
    }

    /* prompt-galaxy-refinements.md #2 -- .sr-ps-aura is a wrapper only
       (carries the breath-synced sr-ps-auraSwell keyframe); the visible
       gradient plus the --amp/--release-responsive scale live on the inner
       div. See css/saferise-poster.css for why one element can't hold both. */
    var aura = el('div', 'sr-ps-aura');
    var auraInner = el('div', 'sr-ps-aura-inner');
    aura.appendChild(auraInner);
    var scrim = el('div', 'sr-ps-scrim');
    var stepnow = el('p', 'sr-ps-stepnow');
    var edge = el('div', 'sr-ps-edge');

    var order = [field, clear, lights, wander];
    if (subjwrap) order.push(subjwrap);
    order.push(aura, scrim, stepnow, edge);
    order.forEach(function (n) { frag.appendChild(n); });
    stage.insertBefore(frag, stage.firstChild);

    return {
      field: field, clear: clear, subject: subject, aura: aura,
      auraInner: auraInner, scrim: scrim, stepnow: stepnow, edge: edge
    };
  }

  function mount(stage, audio, opts) {
    opts = opts || {};

    /* hide the old particle canvases rather than removing them -- see file
       header */
    var oldGlow = stage.querySelector('canvas.sr-glow');
    var oldField = stage.querySelector('canvas.sr-field');
    if (oldGlow) oldGlow.style.display = 'none';
    if (oldField) oldField.style.display = 'none';

    stage.classList.add('sr-ps-stage');

    /* SR-406 · opts.id lets a caller name the protocol explicitly, for the
       case this pass exists to cover: a page that wants the poster mounted
       before any real audio (and therefore any parseable audio.src) exists
       at all. idFromSrc() stays the default so the one already-working
       caller (dashboard.html, via a real <audio src>) needs no change. */
    var id = opts.id || idFromSrc(audio);
    var data = (root.GALAXY_POSTERS && id) ? root.GALAXY_POSTERS[id] : null;

    var warm = (data && data.warm) || opts.warm || [212, 168, 103];
    var cool = (data && data.cool) || opts.cool || [124, 178, 196];
    stage.style.setProperty('--sr-ps-warm', warm.join(','));
    stage.style.setProperty('--sr-ps-cool', cool.join(','));
    stage.style.setProperty('--warmshift', warmShift().toFixed(2));

    var stateAccent = {
      Agitated: 'rgba(201,122,90,.30)', Unsteady: 'rgba(212,168,67,.26)',
      Numb: 'rgba(90,107,132,.32)', Steady: 'rgba(127,168,140,.30)'
    };
    if (data && stateAccent[data.state]) {
      stage.style.setProperty('--sr-ps-acc', stateAccent[data.state]);
    }

    /* v2 #1a -- read straight from the protocol's own state, not a
       per-player data-per attribute. Falls back to 'Agitated' only when
       the id genuinely isn't in the manifest at all (never expected in
       practice -- all 31 ids resolve, confirmed in this pass's own
       report), so there is always a valid keyframe/held-seconds pair. */
    var state = (data && data.state) || 'Agitated';
    var heldBreath = STATE_HELD_BREATH[state] || 10;
    var keyframeSuffix = STATE_KEYFRAME[state] || 'A';
    var reduced = reducedMotion();

    /* #2 -- two tiers, no fallback. hasSubject is the whole tier switch:
       full when the manifest has a cutout, universal otherwise -- checked
       against the manifest's own flagged/field/clear/subject fields, not
       a hardcoded id list, so a protocol upgrades from universal to full
       automatically the moment tools/mk_posters.py produces a subject.png
       for it and content/galaxy.js records it (flagged:false). Every one
       of the 30 track protocols has at least a `cover` (confirmed in this
       pass's own report), so there is always something to show. */
    var hasSubject = !!(data && !data.flagged && data.field && data.clear && data.subject);
    var cover = (data && data.cover) || opts.fallbackCover;
    if (!hasSubject && !cover) return { destroy: function () {} }; /* nothing to show at all */

    var layers = buildLayers(stage, data || { cover: cover }, hasSubject);

    /* v2 #1b -- select the per-state keyframe. Full tier: subject carries
       it. Universal tier: no subject exists, so only the aura carries the
       breath (#2's own instruction) -- still one element/one period/one
       curve, the reason the governing rule permits it at all. Set before
       reading getAnimations() below so the Animation object returned is
       the one actually running under the chosen name. */
    if (layers.subject) layers.subject.style.animationName = 'sr-ps-breathe' + keyframeSuffix;
    layers.aura.style.animationName = 'sr-ps-auraSwell' + keyframeSuffix;

    if (!reduced) applyHeldBreath([layers.subject, layers.aura].filter(Boolean), heldBreath);
    /* Inspectable record of the held value -- not read by anything here
       (playbackRate above is what actually drives speed), but set once,
       never rewritten, so a computed-style check can confirm the period
       equals the state's own pair throughout the session and never drifts. */
    stage.style.setProperty('--breath', heldBreath.toFixed(2) + 's');

    var hasAudio = !!(audio.getAttribute && audio.getAttribute('src'));
    var voiceEl = null, transport = null;
    if (opts.buildControl) {
      var built = buildOverlay(stage, audio, hasAudio, opts.theme, opts.title);
      voiceEl = built.voice;
      buildLock(stage);
      transport = buildTransport(stage, audio, hasAudio);
    }
    var stepSegs = opts.buildControl ? buildSteps(stage) : null;
    if (opts.buildControl) stage.classList.add('sr-ps-player');

    var aura = makeAura(audio);
    var voiceBars = voiceEl ? voiceEl.querySelectorAll('i') : null;

    /* GALAXY-PLAYER-COMPLETE.md #3 -- the --p driver. Confirmed this file
       already had a working one before this pass (an rAF loop polling
       audio.currentTime/duration at ~4Hz, present since SR-403 and
       exercised live in every pass since) -- the brief's "nothing in the
       repo drives --p" does not hold here, reported rather than accepted
       at face value. Its suggested timeupdate listener is still adopted,
       for a real reason found while checking the claim rather than the
       claim itself: rAF throttles to near-zero in a backgrounded tab,
       while timeupdate keeps firing off the audio element's own clock
       regardless of tab visibility -- a real gap for a meditation a
       member might play with the screen off. Both drivers write the same
       --p from the same audio.currentTime/duration; kept the rAF loop too
       since --amp/--release/step/off-screen-pause still need per-frame
       timing, not just per-timeupdate. */
    function computeP() {
      var dur = audio.duration;
      return (dur && isFinite(dur) && dur > 0) ? Math.max(0, Math.min(1, audio.currentTime / dur)) : 0;
    }

    function applyStepsAndRelease(p) {
      var idx = Math.min(3, Math.floor(p * 4));
      var within = (p * 4) - idx;
      if (layers.stepnow) {
        var name = STEPS[idx];
        if (layers.stepnow.textContent !== name) layers.stepnow.textContent = name;
      }
      if (stepSegs) {
        stepSegs.forEach(function (seg, i) {
          seg.classList.toggle('on', i === idx);
          seg.classList.toggle('done', i < idx);
          var w = i < idx ? '100%' : (i === idx ? (within * 100).toFixed(1) + '%' : '0%');
          seg.querySelector('i').style.setProperty('--w', w);
        });
      }
      var release = (idx === 2) ? Math.sin(within * Math.PI) : 0;
      stage.style.setProperty('--release', release.toFixed(3));
    }

    /* FB-07 -- kept out of the dragging member's way: skipped entirely
       while transport.dragging() is true, same as a native scrub bar
       would. Runs from both onTimeupdate (the audio element's own clock,
       so it keeps counting in a backgrounded tab) and frame() below, so
       the visible time/seek position never lags --p's own driver. */
    function applyTransport() {
      if (!transport || transport.dragging()) return;
      var dur = audio.duration;
      transport.cur.textContent = fmtTime(audio.currentTime);
      if (dur && isFinite(dur) && dur > 0) {
        var p2 = Math.max(0, Math.min(1, audio.currentTime / dur));
        transport.seek.value = Math.round(p2 * 1000);
        transport.seek.style.setProperty('--sp', (p2 * 100).toFixed(2) + '%');
        transport.seek.setAttribute('aria-valuetext', fmtTime(audio.currentTime) + ' of ' + fmtTime(dur));
      }
    }

    function onTimeupdate() {
      var p = computeP();
      stage.style.setProperty('--p', p.toFixed(4));
      applyStepsAndRelease(p);
      applyTransport();
    }
    audio.addEventListener('timeupdate', onTimeupdate);

    var raf = null, lastTick = 0, running = false;

    function frame(now) {
      raf = null;
      if (!running) return;
      if (!document.contains(stage)) { teardown(); return; }
      if (now - lastTick >= TICK_MS) {
        lastTick = now;
        var p = computeP();
        stage.style.setProperty('--p', p.toFixed(4));
        applyStepsAndRelease(p);
        applyTransport();
        if (!reduced) {
          var level = aura.read();
          stage.style.setProperty('--amp', level.toFixed(3));
          /* FB-07 -- four bars, each a fixed fraction of the same level
             plus a small per-bar offset so they don't move in lockstep
             (reads as "speaking", not a single meter needle). Still when
             paused: frame() only runs while running is true (see start/
             stop below), so --v simply stops being written. */
          if (voiceBars) {
            for (var vi = 0; vi < voiceBars.length; vi++) {
              var off = [0, .12, .05, .18][vi] || 0;
              var v = Math.max(0, Math.min(1, level * (1 - off) + (Math.sin(now / (240 + vi * 70)) * .08)));
              voiceBars[vi].style.setProperty('--v', v.toFixed(3));
            }
          }
        }
      }
      raf = requestAnimationFrame(frame);
    }

    function start() {
      if (running) return;
      running = true;
      stage.setAttribute('data-sr-ps-playing', 'true');
      stage.classList.add('playing');
      stage.style.setProperty('--playing', '1');
      if (!reduced) aura.connectAnalyser();
      lastTick = 0;
      raf = requestAnimationFrame(frame);
    }
    function stop() {
      running = false;
      stage.setAttribute('data-sr-ps-playing', 'false');
      stage.classList.remove('playing');
      stage.style.setProperty('--playing', '0');
      if (raf) cancelAnimationFrame(raf);
      raf = null;
      aura.disconnectAnalyser();
    }
    /* #3 -- reset on ended and on an explicit reset, never on pause (a
       paused session keeps its position). */
    function reset() {
      stage.style.setProperty('--p', 0);
      stage.style.setProperty('--release', 0);
      if (layers.stepnow) layers.stepnow.textContent = '';
      if (stepSegs) {
        stepSegs.forEach(function (seg) {
          seg.classList.remove('on', 'done');
          seg.querySelector('i').style.setProperty('--w', '0%');
        });
      }
      if (transport) {
        transport.cur.textContent = fmtTime(0);
        transport.seek.value = 0;
        transport.seek.style.setProperty('--sp', '0%');
      }
      if (voiceBars) {
        for (var vr = 0; vr < voiceBars.length; vr++) voiceBars[vr].style.setProperty('--v', 0);
      }
    }

    audio.addEventListener('play', start);
    audio.addEventListener('pause', stop);
    audio.addEventListener('ended', function () { stop(); reset(); });

    /* off-screen: SR-343's own pattern (js/saferise-track.js) -- a
       continuously-toggling IntersectionObserver, not a scroll listener,
       animation-play-state via a class rather than unobserving. */
    var io = null;
    if ('IntersectionObserver' in root) {
      io = new IntersectionObserver(function (entries) {
        entries.forEach(function (e) {
          stage.classList.toggle('sr-ps-off', !e.isIntersecting);
        });
      }, { threshold: 0.12, rootMargin: '0px 0px -8% 0px' });
      io.observe(stage);
    }

    function teardown() {
      stop();
      audio.removeEventListener('play', start);
      audio.removeEventListener('pause', stop);
      audio.removeEventListener('timeupdate', onTimeupdate);
      if (io) io.disconnect();
      aura.teardown();
    }

    /* No explicit destroy hook reaches this file from sr-medplayer.js's own
       close(), so self-check on the next tick after any play/pause churn;
       already covered inside frame() via document.contains(stage). */

    return { destroy: teardown };
  }

  root.SRClearing = { mount: mount };
})(window);
